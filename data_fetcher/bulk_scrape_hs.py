MAX_RETRIES = 3
TIMEOUT = 30


# ── Data Model ─────────────────────────────────────────────────
class HsRecord:
    __slots__ = ("code", "name", "unit", "mfn_rate", "export_rate",
                 "vat_rate", "excise_rate", "supervision", "chapter")

    def __init__(self, code: str, name: str, unit: str = "",
                 mfn_rate: float = 0.0, export_rate: float = 0.0,
                 vat_rate: float = 0.0, excise_rate: float = 0.0,
                 supervision: str = "", chapter: str = ""):
        self.code = code
        self.name = name
        self.unit = unit
        self.mfn_rate = mfn_rate
        self.export_rate = export_rate
        self.vat_rate = vat_rate
        self.excise_rate = excise_rate
        self.supervision = supervision
        self.chapter = chapter or code.split(".")[0]

    def as_dict(self) -> dict:
        return {k: getattr(self, k) for k in self.__slots__}


# ── HTTP Client ────────────────────────────────────────────────
class Fetcher:
    def __init__(self, delay: float = REQUEST_DELAY):
        self.delay = delay
        self.session = requests.Session()
        self.session.headers.update(HEADERS)
        self._last = 0.0

    def _pace(self):
        elapsed = time.monotonic() - self._last
        if elapsed < self.delay:
            time.sleep(self.delay - elapsed)
        self._last = time.monotonic()

    def get(self, url: str, as_json: bool = False) -> Optional[str | dict]:
        for attempt in range(1, MAX_RETRIES + 1):
            try:
                self._pace()
                logger.debug("GET %s (attempt %d)", url[:120], attempt)
                resp = self.session.get(url, timeout=TIMEOUT)
                resp.raise_for_status()
                if as_json:
                    return resp.json()
                resp.encoding = resp.apparent_encoding or "utf-8"
                return resp.text
            except Exception as e:
                logger.warning("Request failed: %s", e)
                if attempt < MAX_RETRIES:
                    time.sleep(2 ** attempt)
        return None


# ── Source 1: china-tariff.com (REST API) ──────────────────────
def scrape_china_tariff_api(fetcher: Fetcher) -> list[HsRecord]:
    """Try the china-tariff.com REST API which returns JSON by chapter."""
    records: list[HsRecord] = []
    base = "https://www.china-tariff.com"

    logger.info("=== Source 1: china-tariff.com API ===")
    for chapter in range(1, 98):
        url = f"{base}/api/tariff/chapter/{chapter:02d}"
        data = fetcher.get(url, as_json=True)
        if not data:
            logger.warning("  Chapter %02d: no data", chapter)
            continue

        items = data.get("data", data.get("items", []))
        for item in items:
            code = item.get("hsCode", item.get("code", ""))
            name = item.get("description", item.get("name", ""))
            if not code or not name:
                continue
            records.append(HsRecord(
                code=code, name=name,
                unit=item.get("unit", ""),
                mfn_rate=float(item.get("mfnRate", item.get("mfn", 0)) or 0),
                export_rate=float(item.get("exportRate", item.get("export", 0)) or 0),
                vat_rate=float(item.get("vatRate", item.get("vat", 0)) or 0),
                chapter=f"{chapter:02d}",
            ))
        logger.info("  Chapter %02d: %d records (total: %d)", chapter, len(items), len(records))

        if len(records) >= BATCH_SIZE:
            break  # test first 100 chapters for rate limiting

    return records


# ── Source 2: hs.e-to-china.com (indexed pages) ────────────────
def scrape_etochina(fetcher: Fetcher) -> list[HsRecord]:
    """Scrape hs.e-to-china.com which has chapter-indexed HS code pages."""
    records: list[HsRecord] = []
    base = "https://hs.e-to-china.com"

    logger.info("=== Source 2: hs.e-to-china.com ===")
    for chapter in range(1, 98):
        url = f"{base}/hs-code-{chapter:02d}.html"
        html = fetcher.get(url)
        if not html:
            logger.warning("  Chapter %02d: fetch failed", chapter)
            continue

        soup = BeautifulSoup(html, "html.parser")
        table = soup.find("table")
        if not table:
            continue

        count = 0
        for row in table.find_all("tr")[1:]:  # skip header
            cells = row.find_all("td")
            if len(cells) < 2:
                continue
            code = cells[0].get_text(strip=True)
            name = cells[1].get_text(strip=True)
            if not re.match(r"\d{4,6}[.]\d{2,4}", code):
                continue

            unit = cells[2].get_text(strip=True) if len(cells) > 2 else ""
            mfn_text = cells[3].get_text(strip=True) if len(cells) > 3 else "0"
            mfn = _parse_rate(mfn_text)

            records.append(HsRecord(
                code=code, name=name, unit=unit,
                mfn_rate=mfn, chapter=f"{chapter:02d}",
            ))
            count += 1

        logger.info("  Chapter %02d: %d records (total: %d)", chapter, count, len(records))
        if len(records) >= BATCH_SIZE:
            break

    return records


