def _parse_rate(text: str) -> float:
    match = re.search(r"(\d+(?:[.]\d+)?)", str(text))
    return float(match.group(1)) if match else 0.0


# ── Main ───────────────────────────────────────────────────────
def main():
    logger.info("=" * 60)
    logger.info("  Bulk HS Code Importer for China Customs Tariff 2024")
    logger.info("=" * 60)

    fetcher = Fetcher()
    all_records: list[HsRecord] = []

    # Try Source 1: china-tariff.com API
    records = scrape_china_tariff_api(fetcher)
    if len(records) >= 500:
        all_records = records
        logger.info("Source 1 success: %d records", len(records))
    else:
        logger.info("Source 1 insufficient (%d records), trying Source 2...", len(records))

    # Try Source 2: hs.e-to-china.com
    if len(all_records) < 500:
        records = scrape_etochina(fetcher)
        if len(records) >= 500:
            all_records = records
            logger.info("Source 2 success: %d records", len(records))
        else:
            logger.info("Source 2 insufficient (%d records), using built-in data...", len(records))

    # Source 3: Built-in comprehensive data (always loaded as supplement)
    builtin = load_comprehensive_builtin()
    logger.info("Built-in data: %d records", len(builtin))

    # Merge: built-in + scraped, deduplicate by code
    seen = set()
    merged: list[HsRecord] = []
    for r in all_records:
        if r.code not in seen:
            seen.add(r.code)
            merged.append(r)
    for r in builtin:
        if r.code not in seen:
            seen.add(r.code)
            merged.append(r)

    logger.info("Total unique HS codes: %d", len(merged))

    # Add chapter metadata
    for r in merged:
        chap_num = int(r.chapter) if r.chapter.isdigit() else 0
        if not r.name and chap_num in CHAPTER_NAMES:
            r.name = f"{CHAPTER_NAMES[chap_num]} — 其他"

    # Sort by code
    merged.sort(key=lambda r: r.code)

    # Export JSON (compatible with seed_hs.ts)
    json_path = OUTPUT_DIR / "hs_codes.json"
    data = [r.as_dict() for r in merged]
    json_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    logger.info("Exported %d records to %s", len(data), json_path)

    # Export CSV
    import csv
    csv_path = OUTPUT_DIR / "hs_codes.csv"
    fieldnames = list(HsRecord.__slots__)
    with open(csv_path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in merged:
            writer.writerow(r.as_dict())
    logger.info("Exported CSV to %s", csv_path)

    # Summary
    print(f"\n{'='*50}")
    print(f"  Done! {len(merged)} HS codes saved.")
    print(f"  JSON: {json_path}")
    print(f"  CSV:  {csv_path}")
    print(f"\n  Next: cd backend && npx tsx ..\\data_fetcher\\seed_hs.ts")


if __name__ == "__main__":
    main()
