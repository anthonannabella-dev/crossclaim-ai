def get_subheadings_for(heading_code: str, heading_desc: str, heading_mfn: float,
                        unit: str, chapter: int) -> list:
    """Generate 6-digit subheadings for a 4-digit heading."""
    # Find matching pattern
    pattern = None
    for p in SUBHEADING_PATTERNS:
        if chapter in p["chapters"]:
            pattern = p
            break

    if not pattern:
        pattern = SUBHEADING_PATTERNS[-1]  # default

    results = []
    for suffix, suffix_desc in pattern["suffixes"]:
        sub_code = f"{heading_code}{suffix}"
        sub_name = f"{heading_desc}（{suffix_desc}）"
        results.append({
            "code": sub_code,
            "name": sub_name,
            "unit": unit,
            "mfn_rate": heading_mfn,
            "chapter": f"{chapter:02d}",
        })
    return results


def expand_to_8digit(code_6: str, desc_6: str, mfn: float, unit: str, chapter: int) -> list:
    """Expand 6-digit code to 8-digit Chinese subheading."""
    results = []
    # China typically adds 2 digits: 00 = primary, 01/90 = alternatives
    sub_codes = [("00", "（主税目）"), ("01", "规格一"), ("90", "其他规格")]
    for suffix, suffix_desc in sub_codes:
        results.append({
            "code": f"{code_6}{suffix}",
            "name": f"{desc_6}{suffix_desc}",
            "unit": unit,
            "mfn_rate": mfn,
            "chapter": f"{chapter:02d}",
        })
    return results


def expand_to_10digit(code_8: str, desc_8: str, mfn: float, unit: str, chapter: int) -> list:
    """Expand 8-digit to 10-digit customs declaration code."""
    results = []
    # 10-digit codes add 2 more digits for customs declaration detail
    sub_codes = [("00", "（一般贸易）"), ("10", "进料加工"), ("20", "来料加工"), ("90", "其他贸易方式")]
    for suffix, suffix_desc in sub_codes:
        results.append({
            "code": f"{code_8}{suffix}",
            "name": f"{desc_8}{suffix_desc}",
            "unit": unit,
            "mfn_rate": mfn,
            "chapter": f"{chapter:02d}",
        })
    return results


