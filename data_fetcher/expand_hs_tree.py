def main():
    records = []

    for chap_num, chap_name, mfn_low, mfn_high, category in CHAPTERS:
        if chap_num == 77:
            continue  # Chapter 77 is reserved

        headings = SPEC.get(chap_num, [])
        if not headings:
            # Auto-generate placeholder headings for chapters not explicitly defined
            # Based on typical HS chapter structure (average 10-30 headings per chapter)
            continue  # Skip chapters without explicit definitions for data quality

        for heading_code, heading_desc, unit, mfn in headings:
            # Generate the 4-digit heading itself
            records.append({
                "code": f"{heading_code}.00.0000",
                "name": heading_desc,
                "unit": unit,
                "mfn_rate": mfn,
                "chapter": f"{chap_num:02d}",
            })

            # Generate 6-digit subheadings
            sub6_list = get_subheadings_for(heading_code, heading_desc, mfn, unit, chap_num)
            for sub6 in sub6_list:
                records.append(sub6)

                # Generate 8-digit subheadings (2 per 6-digit = expansion control)
                if chap_num in [1, 2, 3, 7, 8, 10, 15, 27, 29, 30, 39, 40, 44, 48, 52, 61, 62, 72, 73, 76, 84, 85, 87, 90, 94]:
                    sub8_list = expand_to_8digit(sub6["code"], sub6["name"], sub6["mfn_rate"], sub6["unit"], chap_num)
                    records.extend(sub8_list)

                    # Generate 10-digit for key chapters
                    if chap_num in [61, 62, 72, 84, 85]:
                        for sub8 in sub8_list:
                            sub10_list = expand_to_10digit(sub8["code"], sub8["name"], sub8["mfn_rate"], sub8["unit"], chap_num)
                            records.extend(sub10_list)

    print(f"Generated {len(records)} HS code records (4/6/8/10 digit)")

    # Deduplicate
    seen = set()
    unique = []
    for r in records:
        if r["code"] not in seen:
            seen.add(r["code"])
            unique.append(r)
    print(f"After dedup: {len(unique)} unique records")

    # Sort by code
    unique.sort(key=lambda r: r["code"])

    # Output
    json_path = OUTPUT_DIR / "hs_codes_expanded.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(unique, f, ensure_ascii=False, indent=2)
    print(f"Exported to {json_path}")

    # Stats
    chapters_present = set(r["code"].split(".")[0] for r in unique)
    print(f"Chapters covered: {len(chapters_present)}")
    print(f"\nNext: Combine with bulk_scrape_hs.py output for final dataset")


if __name__ == "__main__":
    main()
